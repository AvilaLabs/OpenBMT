//! The one table of `docs/screens/owner.md`, shared by the four crates of
//! the owner's side. Each crate owns the rows that start with its own
//! prefix; writing the file replaces only those rows and keeps the rest.
//! The other crates include this file with `#[path]`, so it exists once.

/// The prefixes of the four crates, in the order their rows are written.
pub const PREFIXES: [&str; 4] = ["owner", "spend", "books", "pos"];

/// The head of the table, with the lines above it.
const HEAD: &str = "# Owner: every screen of the library crates\n\
\n\
Generated by the tests of `openbmt-owner`, `openbmt-spend`, `openbmt-books`\n\
and `openbmt-pos` (SC-12). Each crate writes its own rows, those that start\n\
with its name before the colon. Do not edit by hand: run the tests with\n\
`OPENBMT_WRITE_SCREENS=1` (one crate after the other) to write them again.\n\
\n\
| state | heading | what happened | what to do next | who | code |\n\
|---|---|---|---|---|---|\n";

/// The rows of one crate, from the lines of the file.
pub fn rows_of(file: &str, prefix: &str) -> Vec<String> {
    let start = format!("| {prefix}: ");
    file.lines()
        .filter(|l| l.starts_with(&start))
        .map(str::to_string)
        .collect()
}

/// The file as it is after the rows of `prefix` were replaced by `rows`.
pub fn merged(existing: &str, prefix: &str, rows: &str) -> String {
    let mut out = String::from(HEAD);
    for p in PREFIXES {
        if p == prefix {
            out.push_str(rows);
        } else {
            for line in rows_of(existing, p) {
                out.push_str(&line);
                out.push('\n');
            }
        }
    }
    out
}

/// SC-12: compare the rows of one crate with the file on disk, or, when the
/// environment has `OPENBMT_WRITE_SCREENS=1`, write them into it.
pub fn check_or_write(prefix: &str, rows: &str) {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/screens/owner.md");
    let existing = std::fs::read_to_string(&path).unwrap_or_default();
    if std::env::var("OPENBMT_WRITE_SCREENS").is_ok_and(|v| v == "1") {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).expect("the screens folder can be made");
        }
        std::fs::write(&path, merged(&existing, prefix, rows)).expect("the file can be written");
        return;
    }
    let now: Vec<String> = rows.lines().map(str::to_string).collect();
    assert_eq!(
        rows_of(&existing, prefix),
        now,
        "docs/screens/owner.md is out of date for `{prefix}`: run the tests of this crate with \
         OPENBMT_WRITE_SCREENS=1 to write it again"
    );
}
